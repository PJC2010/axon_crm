/**
 * Scopes Blueprint's global stylesheet under `.lp-root` so it only affects
 * the landing page and never leaks onto the rest of the app (login,
 * dashboard, etc.). Run with: `node scripts/scope-blueprint-css.mjs`
 *
 * Every selector is prefixed with `.lp-root`. Global selectors that can't be
 * descendants (`:root`, `html`, `body`) are mapped onto the container itself.
 * Keyframe steps are left untouched.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import postcss from 'postcss'

const require = createRequire(import.meta.url)
const SCOPE = '.lp-root'

const src = require.resolve('@blueprintjs/core/lib/css/blueprint.css')
const css = readFileSync(src, 'utf8')

function scopeSelector(sel) {
  const s = sel.trim()
  if (s === ':root' || s === 'html' || s === 'body') return SCOPE
  // compound starting with html/body (e.g. `body.bp6-overlay-open`)
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)/, SCOPE)
  return `${SCOPE} ${s}`
}

const root = postcss.parse(css)

// Drop @charset — it must be the file's first byte, which our header prevents.
root.walkAtRules('charset', (at) => at.remove())

root.walkRules((rule) => {
  // Skip keyframe steps (from/to/percentages).
  if (rule.parent && rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) {
    return
  }
  rule.selectors = rule.selectors.map(scopeSelector)
})

const header = '/* AUTO-GENERATED by scripts/scope-blueprint-css.mjs — do not edit by hand.\n' +
  '   Blueprint core CSS, scoped under .lp-root so it never leaks app-wide. */\n'

writeFileSync(new URL('../app/blueprint-scoped.css', import.meta.url), header + root.toString())
console.log('Wrote app/blueprint-scoped.css')
