/**
 * Builds an app-wide Blueprint stylesheet for the authenticated app.
 *
 * Unlike app/blueprint-scoped.css (scoped under .lp-root for the landing
 * page), this keeps Blueprint's `.bp6-*` component rules global — they're
 * already namespaced by the `bp6-` prefix, so they only match Blueprint
 * components — but REMOVES Blueprint's bare-element base rules
 * (html, body, a, p, universal, selection, focus) so they never override the
 * app's own base typography defined in globals.css.
 *
 * Run with: `node scripts/build-blueprint-app-css.mjs`
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import postcss from 'postcss'

const require = createRequire(import.meta.url)

// Bare selectors whose rules conflict with the app's own base styles.
const DROP = new Set([
  'html', 'body', 'a', 'a:hover', 'a code', 'p', 'small', 'strong', 'form',
  '*', '*::before', '*::after', '::selection', '::-moz-selection', ':focus',
])

const src = require.resolve('@blueprintjs/core/lib/css/blueprint.css')
const root = postcss.parse(readFileSync(src, 'utf8'))

root.walkAtRules('charset', (at) => at.remove())

root.walkRules((rule) => {
  if (rule.parent && rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return
  const kept = rule.selectors.filter((s) => !DROP.has(s.trim()))
  if (kept.length === 0) {
    rule.remove()
  } else {
    rule.selectors = kept
  }
})

const header = '/* AUTO-GENERATED by scripts/build-blueprint-app-css.mjs — do not edit by hand.\n' +
  '   Blueprint component CSS for the app; bare-element base rules removed so it\n' +
  '   is safe to load globally (only .bp6-* classes are styled). */\n'

writeFileSync(new URL('../app/blueprint-app.css', import.meta.url), header + root.toString())
console.log('Wrote app/blueprint-app.css')
